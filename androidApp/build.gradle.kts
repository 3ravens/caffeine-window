// Upload-key settings come from the untracked local.properties or from environment
// variables (CI). Without them, release builds are produced unsigned.
val localProperties = Properties().apply {
    val file = rootProject.file("local.properties")
    if (file.exists()) file.inputStream().use { load(it) }
}

fun signingValue(property: String, env: String): String? =
    localProperties.getProperty(property) ?: System.getenv(env)

val uploadStoreFile = signingValue("upload.storeFile", "CW_UPLOAD_STORE_FILE")

android {
    namespace = "com.caffeinewindow.app"
    compileSdk = 36

    defaultConfig {
        applicationId = "com.caffeinewindow.app"
        minSdk = 26
        targetSdk = 36
        versionCode = 2
        versionName = "1.0.1"

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    signingConfigs {
        if (uploadStoreFile != null) {
            create("upload") {
                storeFile = file(uploadStoreFile)
                storePassword = signingValue("upload.storePassword", "CW_UPLOAD_STORE_PASSWORD")
                keyAlias = signingValue("upload.keyAlias", "CW_UPLOAD_KEY_ALIAS")
                keyPassword = signingValue("upload.keyPassword", "CW_UPLOAD_KEY_PASSWORD")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            signingConfig = signingConfigs.findByName("upload")
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro",
            )
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
    }

    packaging {
        resources {
            excludes += "/META-INF/{AL2.0,LGPL2.1}"
        }
    }
}

